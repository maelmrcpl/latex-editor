import type { ProjectTemplateId } from '@prism-latex/shared';

export interface TemplateDefinition {
  id: ProjectTemplateId;
  rootFile: string;
  files: Record<string, string>;
}

export function getTemplateFiles(templateId: ProjectTemplateId, title: string): TemplateDefinition {
  const safeTitle = title.replace(/[\\{}%$&#_^~]/g, '') || 'Document Scientifique';

  switch (templateId) {
    case 'article':
      return {
        id: 'article',
        rootFile: 'main.tex',
        files: {
          'main.tex': [
            '\\documentclass[11pt,a4paper]{article}',
            '\\usepackage[utf8]{inputenc}',
            '\\usepackage[T1]{fontenc}',
            '\\usepackage{amsmath,amssymb,amsthm}',
            '\\usepackage{graphicx}',
            '\\usepackage{hyperref}',
            '\\usepackage{geometry}',
            '\\geometry{margin=2.5cm}',
            '',
            '\\newtheorem{theorem}{Theorem}[section]',
            '\\newtheorem{lemma}[theorem]{Lemma}',
            '',
            `\\title{${safeTitle}}`,
            '\\author{Research Paper}',
            '\\date{\\today}',
            '',
            '\\begin{document}',
            '',
            '\\maketitle',
            '',
            '\\begin{abstract}',
            'This paper demonstrates real-time client-side WebAssembly \\LaTeX{} compilation with multi-file support, mathematical typesetting, Sync\\TeX{} navigation, and bibliography management.',
            '\\end{abstract}',
            '',
            '\\input{sections/introduction}',
            '',
            '\\section{Mathematical Formulation}',
            '\\label{sec:math}',
            '',
            'Let $\\mathcal{H}$ be a Hilbert space and consider the Gaussian integral:',
            '\\begin{equation}',
            '  \\label{eq:gaussian}',
            '  \\int_{-\\infty}^{\\infty} e^{-\\alpha x^2} \\, dx = \\sqrt{\\frac{\\pi}{\\alpha}}, \\quad \\Re(\\alpha) > 0.',
            '\\end{equation}',
            '',
            '\\begin{theorem}[Spectral Decomposition]',
            '\\label{thm:spectral}',
            'Every compact self-adjoint operator $T : \\mathcal{H} \\to \\mathcal{H}$ admits an orthonormal basis of eigenvectors. As shown in Equation~\\eqref{eq:gaussian} and foundational work~\\cite{vaswani2017attention}, structured representations simplify analysis.',
            '\\end{theorem}',
            '',
            '\\bibliographystyle{plain}',
            '\\bibliography{references}',
            '',
            '\\end{document}',
            '',
          ].join('\n'),
          'sections/introduction.tex': [
            '\\section{Introduction}',
            '\\label{sec:intro}',
            '',
            'Welcome to your SynTeX \\LaTeX{} workspace. Everything in this project compiles directly inside your browser via WebAssembly, keeping your Proxmox LXC server lightweight.',
            '',
            '\\begin{itemize}',
            '  \\item Use \\textbf{Ctrl+Enter} (or \\textbf{Ctrl+S}) to trigger compilation at any time.',
            '  \\item \\textbf{Ctrl+Click} anywhere on the PDF preview to jump back to the exact \\LaTeX{} line.',
            '  \\item Open the \\textbf{Citations} tab in the left sidebar to search \\emph{arXiv} and \\emph{Crossref} and insert Bib\\TeX{} entries in one click.',
            '\\end{itemize}',
            '',
            'See Section~\\ref{sec:math} and Theorem~\\ref{thm:spectral} for examples of cross-references.',
            '',
          ].join('\n'),
          'references.bib': [
            '@inproceedings{vaswani2017attention,',
            '  title={Attention Is All You Need},',
            '  author={Vaswani, Ashish and Shazeer, Noam and Parmar, Niki and Uszkoreit, Jakob and Jones, Llion and Gomez, Aidan N and Kaiser, {\\L}ukasz and Polosukhin, Illia},',
            '  booktitle={Advances in Neural Information Processing Systems},',
            '  volume={30},',
            '  year={2017}',
            '}',
            '',
            '@book{knuth1984texbook,',
            '  title={The TeXbook},',
            '  author={Knuth, Donald Ervin},',
            '  year={1984},',
            '  publisher={Addison-Wesley}',
            '}',
            '',
          ].join('\n'),
        },
      };

    case 'report-fr':
      return {
        id: 'report-fr',
        rootFile: 'main.tex',
        files: {
          'main.tex': [
            '\\documentclass[11pt,a4paper]{report}',
            '\\usepackage[utf8]{inputenc}',
            '\\usepackage[T1]{fontenc}',
            '\\usepackage{amsmath,amssymb}',
            '\\usepackage{graphicx}',
            '\\usepackage{hyperref}',
            '\\usepackage{geometry}',
            '\\geometry{margin=2.5cm}',
            '',
            `\\title{${safeTitle}}`,
            '\\author{Maël}',
            '\\date{\\today}',
            '',
            '\\begin{document}',
            '',
            '\\maketitle',
            '\\tableofcontents',
            '',
            '\\input{chapitres/introduction}',
            '',
            '\\chapter{Modélisation et Résultats}',
            '\\label{chap:model}',
            '',
            "Considérons l'équation d'Euler-Lagrange associée au lagrangien $\\mathcal{L}(q, \\dot{q}, t)$ :",
            '\\begin{equation}',
            '  \\label{eq:euler-lagrange}',
            '  \\frac{d}{dt}\\left(\\frac{\\partial \\mathcal{L}}{\\partial \\dot{q}_i}\\right) - \\frac{\\partial \\mathcal{L}}{\\partial q_i} = 0.',
            '\\end{equation}',
            '',
            "Nous faisons référence aux travaux fondateurs de Knuth~\\cite{knuth1984texbook} ainsi qu'à l'équation~\\eqref{eq:euler-lagrange}.",
            '',
            '\\bibliographystyle{plain}',
            '\\bibliography{references}',
            '',
            '\\end{document}',
            '',
          ].join('\n'),
          'chapitres/introduction.tex': [
            '\\chapter{Introduction}',
            '\\label{chap:intro}',
            '',
            "Ce rapport est structuré en plusieurs fichiers \\texttt{.tex} afin de faciliter l'organisation de documents longs (mémoires, rapports d'ingénieur, thèses).",
            '',
            'Le chapitre~\\ref{chap:model} présente le modèle mathématique principal.',
            '',
          ].join('\n'),
          'references.bib': [
            '@book{knuth1984texbook,',
            '  title={The TeXbook},',
            '  author={Knuth, Donald Ervin},',
            '  year={1984},',
            '  publisher={Addison-Wesley}',
            '}',
            '',
          ].join('\n'),
        },
      };

    case 'beamer':
      return {
        id: 'beamer',
        rootFile: 'main.tex',
        files: {
          'main.tex': [
            '\\documentclass[aspectratio=169]{beamer}',
            '\\usetheme{Madrid}',
            '\\usepackage[utf8]{inputenc}',
            '\\usepackage[T1]{fontenc}',
            '\\usepackage{amsmath,amssymb}',
            '',
            `\\title{${safeTitle}}`,
            '\\subtitle{Présentation Scientifique}',
            '\\author{Maël}',
            '\\date{\\today}',
            '',
            '\\begin{document}',
            '',
            '\\begin{frame}',
            '  \\titlepage',
            '\\end{frame}',
            '',
            '\\begin{frame}{Plan de la présentation}',
            '  \\tableofcontents',
            '\\end{frame}',
            '',
            '\\section{Contexte}',
            '\\begin{frame}{Compilation WebAssembly Locale}',
            '  \\begin{itemize}',
            '    \\item Compilation ultra-légère côté navigateur',
            '    \\item Support natif des mathématiques et de Beamer',
            '    \\item Synchronisation directe code $\\leftrightarrow$ diapositives',
            '  \\end{itemize}',
            "  \\begin{block}{Identité d'Euler}",
            '    $$e^{i\\pi} + 1 = 0$$',
            '  \\end{block}',
            '\\end{frame}',
            '',
            '\\end{document}',
            '',
          ].join('\n'),
        },
      };

    case 'blank':
    default:
      return {
        id: 'blank',
        rootFile: 'main.tex',
        files: {
          'main.tex': [
            '\\documentclass[11pt,a4paper]{article}',
            '\\usepackage[utf8]{inputenc}',
            '\\usepackage[T1]{fontenc}',
            '\\usepackage{amsmath}',
            '',
            `\\title{${safeTitle}}`,
            '\\author{}',
            '\\date{\\today}',
            '',
            '\\begin{document}',
            '',
            '\\maketitle',
            '',
            '\\section{Introduction}',
            'Write your \\LaTeX{} content here.',
            '',
            '\\end{document}',
            '',
          ].join('\n'),
        },
      };
  }
}
